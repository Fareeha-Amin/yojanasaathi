export function tr(lang, key, vars) {
  const s = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}

/** The language a typed message is written in: its script, else null (Latin = ambiguous). */
export function scriptLang(text) {
  let kn = 0, hi = 0;
  for (const ch of text) {
    const c = ch.codePointAt(0);
    if (c >= 0x0c80 && c < 0x0d00) kn++;
    else if (c >= 0x0900 && c < 0x0980) hi++;
  }
  if (!kn && !hi) return null;
  return kn >= hi ? "kn" : "hi";
}
